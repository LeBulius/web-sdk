/** Literal `new URL` entries so Vite emits every builder output. */
export function renderManifest(relativePaths: string[]): string {
	const unique = [...new Set(relativePaths)].sort();
	const lines = unique.map(
		(entry) => `\t${JSON.stringify(entry)}: new URL(${JSON.stringify('./' + entry)}, import.meta.url).href,`,
	);
	return `// Generated by layout-editor. Literal URLs so Vite emits builder outputs.\nexport const builderAssets = {\n${lines.join('\n')}\n};\n`;
}

export function collectAssetPaths(value: unknown, into: Set<string> = new Set()): Set<string> {
	if (typeof value === 'string') {
		if (isBuilderRelativePath(value)) into.add(value.replace(/\\/g, '/'));
		return into;
	}
	if (Array.isArray(value)) {
		for (const entry of value) collectAssetPaths(entry, into);
		return into;
	}
	if (value && typeof value === 'object') {
		for (const entry of Object.values(value)) collectAssetPaths(entry, into);
	}
	return into;
}

export function isBuilderRelativePath(value: string): boolean {
	if (!value || value.startsWith('/') || value.startsWith('src/') || value.startsWith('static/')) return false;
	if (value.split('/').includes('..')) return false;
	return /^(art|spine|audio)\//.test(value);
}
