/**
 * Placeholder cues for the one Howler sprite.
 * Original wavs stay in assets-src/audio and are not shipped.
 * Outputs: src/assets/builder/audio/sprite/sprite.m4a, sprite.ogg, sounds.json.
 * Cue names are drafts. audio.placeholders is true.
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const locked = path.join(root, 'apps/locked');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'audio-sprite-'));

const cues = [
	['sfx_contraband_swap', 'sfx', 494, 0.16],
	['sfx_reel_stop', 'sfx', 330, 0.1],
	['sfx_fire_place', 'sfx', 740, 0.09],
	['sfx_ew_expand', 'sfx', 220, 0.14],
	['sfx_win_small', 'sfx', 880, 0.18],
	['sfx_tumble_explode', 'sfx', 160, 0.12],
	['jng_fs_intro', 'jingle', 523, 0.32],
	['jng_fs_retrigger', 'jingle', 659, 0.26],
	...Array.from({ length: 9 }, (_, index) => [`jng_win_lvl${index + 1}`, 'jingle', 420 + index * 36, 0.2]),
	['bgm_base', 'music', 110, 1],
	['bgm_fs', 'music', 146, 1],
	['bgm_degen', 'music', 92, 1],
];

function run(args) {
	const result = spawnSync('ffmpeg', args, { encoding: 'utf8' });
	if (result.status !== 0) {
		throw new Error(result.stderr || result.stdout || 'ffmpeg failed');
	}
}

function probe(file) {
	const result = spawnSync(
		'ffprobe',
		['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file],
		{ encoding: 'utf8' },
	);
	if (result.status !== 0) throw new Error(result.stderr || 'ffprobe failed');
	return Number(result.stdout.trim());
}

const parts = [];
const files = {};
let cursor = 0;

for (const [name, channel, freq, dur] of cues) {
	const originalDir = path.join(locked, 'assets-src/audio', name);
	fs.mkdirSync(originalDir, { recursive: true });
	const original = path.join(originalDir, `${name}.wav`);
	const channels = channel === 'music' ? 2 : 1;
	run([
		'-y',
		'-hide_banner',
		'-loglevel',
		'error',
		'-f',
		'lavfi',
		'-i',
		`sine=frequency=${freq}:duration=${dur}:sample_rate=44100`,
		'-ac',
		String(channels),
		'-c:a',
		'pcm_s16le',
		original,
	]);
	const part = path.join(tmp, `${name}.wav`);
	const loudness = channel === 'music' ? '-18' : '-16';
	const filter =
		channel === 'music'
			? `loudnorm=I=${loudness}:TP=-1:LRA=11`
			: `silenceremove=start_periods=1:start_threshold=-60dB:stop_periods=1:stop_threshold=-60dB,loudnorm=I=${loudness}:TP=-1:LRA=11`;
	run([
		'-y',
		'-hide_banner',
		'-loglevel',
		'error',
		'-i',
		original,
		'-af',
		filter,
		'-ac',
		'2',
		'-ar',
		'44100',
		'-c:a',
		'pcm_s16le',
		part,
	]);
	const duration = probe(part);
	const durationMs = Math.max(1, Math.round(duration * 1000));
	files[name] = {
		channel,
		gainDb: 0,
		loop: channel === 'music',
		placeholder: true,
		startMs: cursor,
		durationMs,
	};
	cursor += durationMs;
	parts.push(part);
}

const list = path.join(tmp, 'list.txt');
fs.writeFileSync(list, parts.map((part) => `file '${part}'`).join('\n'));
const joined = path.join(tmp, 'joined.wav');
run(['-y', '-hide_banner', '-loglevel', 'error', '-f', 'concat', '-safe', '0', '-i', list, '-c', 'copy', joined]);

const outDir = path.join(locked, 'src/assets/builder/audio/sprite');
fs.mkdirSync(outDir, { recursive: true });
const m4a = path.join(outDir, 'sprite.m4a');
const ogg = path.join(outDir, 'sprite.ogg');
run(['-y', '-hide_banner', '-loglevel', 'error', '-i', joined, '-c:a', 'aac', '-b:a', '128k', '-ac', '2', m4a]);
run(['-y', '-hide_banner', '-loglevel', 'error', '-i', joined, '-c:a', 'libopus', '-b:a', '96k', '-ac', '2', ogg]);

const detect = spawnSync('ffmpeg', ['-hide_banner', '-i', m4a, '-af', 'volumedetect', '-f', 'null', '-'], {
	encoding: 'utf8',
});
const peakMatch = detect.stderr.match(/max_volume:\s*(-?\d+(?:\.\d+)?)\s*dB/);
const peakDb = peakMatch ? Number(peakMatch[1]) : -1;

const spriteMap = {};
for (const [name, file] of Object.entries(files)) spriteMap[name] = [file.startMs, file.durationMs];
const sounds = {
	src: ['sprite.m4a', 'sprite.ogg'],
	sprite: spriteMap,
	placeholders: true,
	note: 'One Howler sprite. Placeholder tones, not Locked In recordings. SlotMath / SFX can replace the cue files and rebuild.',
};
fs.writeFileSync(path.join(outDir, 'sounds.json'), JSON.stringify(sounds, null, '\t') + '\n');

fs.writeFileSync(
	path.join(locked, 'assets-src/audio/NOTICE.txt'),
	`Placeholder tones generated by packages/layout-editor/scripts/audio-placeholders.mjs.\nWav originals stay in this folder and are not shipped. The game plays one m4a/ogg sprite.\n`,
);

const builderPath = path.join(locked, 'src/game/builder.json');
const builder = JSON.parse(fs.readFileSync(builderPath, 'utf8'));
builder.audio = {
	version: 1,
	placeholders: true,
	sprite: {
		src: 'audio/sprite/sprite.m4a',
		fallback: 'audio/sprite/sprite.ogg',
		map: 'audio/sprite/sounds.json',
		peakDb,
	},
	files,
	events: {
		reveal: [{ cue: 'sfx_reel_stop', on: 'perReelStop', staggerMs: 80 }],
		fireFramesPlaced: [{ cue: 'sfx_fire_place', on: 'perItem', staggerMs: 60, maxVoices: 3 }],
		contrabandSwap: [{ cue: 'sfx_contraband_swap', on: 'once' }],
		newExpandingWilds: [{ cue: 'sfx_ew_expand', on: 'perItem', staggerMs: 80 }],
		winInfo: [{ cue: 'sfx_win_small', on: 'once' }],
		setWin: [],
		tumbleBoard: [{ cue: 'sfx_tumble_explode', on: 'once' }],
		freeSpinTrigger: [{ cue: 'jng_fs_intro', on: 'once', duckMusicDb: -12 }],
		freeSpinRetrigger: [{ cue: 'jng_fs_retrigger', on: 'once' }],
	},
	silent: ['finalWin', 'freeSpinEnd', 'setTotalWin', 'updateFreeSpin', 'updateGrid', 'wincap'],
	winlevels: Object.fromEntries(Array.from({ length: 9 }, (_, index) => [String(index + 1), `jng_win_lvl${index + 1}`])),
	music: {
		base: { cue: 'bgm_base', crossfadeMs: 800 },
		bonus: { cue: 'bgm_fs', crossfadeMs: 800 },
		degen_spin: { cue: 'bgm_degen', crossfadeMs: 600 },
	},
	mix: {
		phone: { musicDb: -10, sfxDb: -3, jingleDb: -2 },
		desktop: { musicDb: -8, sfxDb: -4, jingleDb: -3 },
	},
	rules: { ducking: [{ when: 'jingle', music: -12, releaseMs: 400 }], maxConcurrentSfx: 6 },
};
fs.writeFileSync(builderPath, JSON.stringify(builder, null, '\t') + '\n');

const manifestPath = path.join(locked, 'src/assets/builder/manifest.ts');
const manifest = fs.readFileSync(manifestPath, 'utf8');
const existing = new Set([...manifest.matchAll(/"((?:art|spine|audio)\/[^"]+)"/g)].map((match) => match[1]));
for (const entry of ['audio/sprite/sounds.json', 'audio/sprite/sprite.m4a', 'audio/sprite/sprite.ogg']) existing.add(entry);
const lines = [...existing].sort().map(
	(entry) => `\t${JSON.stringify(entry)}: new URL(${JSON.stringify('./' + entry)}, import.meta.url).href,`,
);
fs.writeFileSync(
	manifestPath,
	`// Generated by layout-editor. Literal URLs so Vite emits builder outputs.\nexport const builderAssets = {\n${lines.join('\n')}\n};\n`,
);

console.log(`sprite cues ${cues.length} peak ${peakDb} dBFS m4a ${fs.statSync(m4a).size} ogg ${fs.statSync(ogg).size}`);
