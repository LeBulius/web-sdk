/**
 * Demo placeholders for the backgrounds, board frame, and logo the reference
 * game shipped as PNG. These are not Stake-approved art. Originals stay in
 * assets-src. Outputs are WebP under src/assets/builder.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const game = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../apps/locked');

const backgrounds = [
	['background_base', 'base', 0x1a120c],
	['background_3s', 'bg3s', 0x1a2a1c],
	['background_4s', 'bg4s', 0x1a1a2c],
	['background_5s', 'bg5s', 0x2a1a1c],
	['background_start', 'start', 0x141820],
	['background_degen', 'degen', 0x3a1020],
];

function rgb(hex) {
	return { r: (hex >> 16) & 255, g: (hex >> 8) & 255, b: hex & 255 };
}

async function writePair(id, filename, image) {
	const png = await image.clone().png().toBuffer();
	const meta = await sharp(png).metadata();
	const stats = await sharp(png).stats();
	const lossless = stats.isOpaque === false;
	const webp = await sharp(png)
		.webp(lossless ? { lossless: true, quality: 100, effort: 4, exact: true } : { quality: 90, effort: 4 })
		.toBuffer();
	const originalDir = path.join(game, 'assets-src/art', id);
	const outDir = path.join(game, 'src/assets/builder/art', id);
	await fs.mkdir(originalDir, { recursive: true });
	await fs.mkdir(outDir, { recursive: true });
	const webpName = filename.replace(/\.png$/, '.webp');
	await fs.writeFile(path.join(originalDir, filename), png);
	await fs.writeFile(path.join(outDir, webpName), webp);
	return {
		src: `art/${id}/${webpName}`,
		w: meta.width ?? 0,
		h: meta.height ?? 0,
		anchor: [0.5, 0.5],
		placeholder: true,
	};
}

async function plate(w, h, color) {
	return sharp({ create: { width: w, height: h, channels: 3, background: rgb(color) } });
}

async function framed() {
	const w = 64;
	const h = 64;
	const raw = Buffer.alloc(w * h * 4, 0);
	for (let y = 0; y < h; y += 1) {
		for (let x = 0; x < w; x += 1) {
			const edge = x < 4 || y < 4 || x >= w - 4 || y >= h - 4;
			if (!edge) continue;
			const i = (y * w + x) * 4;
			raw[i] = 197;
			raw[i + 1] = 208;
			raw[i + 2] = 220;
			raw[i + 3] = 255;
		}
	}
	return sharp(raw, { raw: { width: w, height: h, channels: 4 } });
}

async function logo() {
	const w = 48;
	const h = 16;
	const raw = Buffer.alloc(w * h * 4, 0);
	for (let y = 4; y < 12; y += 1) {
		for (let x = 4; x < 44; x += 1) {
			const i = (y * w + x) * 4;
			raw[i] = 246;
			raw[i + 1] = 237;
			raw[i + 2] = 216;
			raw[i + 3] = 255;
		}
	}
	return sharp(raw, { raw: { width: w, height: h, channels: 4 } });
}

const slots = {
	board_fireRim: { anchor: [0.5, 0.5], lockToCell: 2 },
};
for (const [id, name, color] of backgrounds) {
	slots[id] = await writePair(id, `${name}.png`, await plate(64, 36, color));
	slots[`${id}_mobile`] = await writePair(`${id}_mobile`, `${name}_mobile.png`, await plate(36, 64, color));
}
slots.board_frame = await writePair('board_frame', 'frame.png', await framed());
slots.screen_logo = await writePair('screen_logo', 'logo.png', await logo());

const builderPath = path.join(game, 'src/game/builder.json');
const builder = JSON.parse(await fs.readFile(builderPath, 'utf8'));
builder.art = {
	...builder.art,
	slots,
	moods: {
		base: 'background_base',
		'3s': 'background_3s',
		'4s': 'background_4s',
		'5s': 'background_5s',
		start: 'background_start',
		degen: 'background_degen',
	},
	placeholders: true,
};
await fs.writeFile(builderPath, JSON.stringify(builder, null, '\t') + '\n');

const paths = new Set(['art/mark/mark.webp']);
for (const entry of Object.values(slots)) {
	if (entry.src) paths.add(entry.src);
}
const lines = [...paths].sort().map(
	(entry) => `\t${JSON.stringify(entry)}: new URL(${JSON.stringify('./' + entry)}, import.meta.url).href,`,
);
const manifest = `// Generated by layout-editor. Literal URLs so Vite emits builder outputs.\nexport const builderAssets = {\n${lines.join('\n')}\n};\n`;
await fs.writeFile(path.join(game, 'src/assets/builder/manifest.ts'), manifest);
console.log(`wrote ${paths.size} art outputs`);
