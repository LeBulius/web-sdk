import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '../../..');
const appRoot = path.resolve(repoRoot, process.argv[2] ?? 'apps/locked');
const builderPath = path.join(appRoot, 'src/game/builder.json');
const outputRoot = path.join(appRoot, 'src/assets/builder');

const builder = JSON.parse(await fs.readFile(builderPath, 'utf8'));
const referenced = new Set();

const walk = (value) => {
	if (typeof value === 'string' && /^(art|spine|audio)\//.test(value) && !value.split('/').includes('..')) {
		referenced.add(value);
	} else if (Array.isArray(value)) value.forEach(walk);
	else if (value && typeof value === 'object') Object.values(value).forEach(walk);
};
walk(builder);

async function filesIn(dir) {
	const found = [];
	let entries = [];
	try {
		entries = await fs.readdir(dir, { withFileTypes: true });
	} catch (error) {
		if (error.code === 'ENOENT') return found;
		throw error;
	}
	for (const entry of entries) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) found.push(...(await filesIn(full)));
		else if (entry.isFile()) found.push(full);
	}
	return found;
}

const removed = [];
const kept = [];
for (const file of await filesIn(outputRoot)) {
	const rel = path.relative(outputRoot, file).split(path.sep).join('/');
	if (rel === 'manifest.ts' || referenced.has(rel)) {
		kept.push(rel);
		continue;
	}
	await fs.rm(file, { force: true });
	removed.push(rel);
}

const lines = [...referenced].sort().map(
	(entry) => `\t${JSON.stringify(entry)}: new URL(${JSON.stringify('./' + entry)}, import.meta.url).href,`,
);
const manifest = `// Generated by layout-editor. Literal URLs so Vite emits builder outputs.\nexport const builderAssets = {\n${lines.join('\n')}\n};\n`;
await fs.mkdir(outputRoot, { recursive: true });
await fs.writeFile(path.join(outputRoot, 'manifest.ts'), manifest);

console.log(JSON.stringify({ removed, kept }, null, 2));
